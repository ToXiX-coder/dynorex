import fs from "node:fs";
import path from "node:path";
import { emptyDb, type Db } from "./types";

/**
 * The only thing services know about persistence. A real database adapter
 * (for example Postgres with row-level security) would implement this same interface.
 */
export interface DataStore {
  /** Read without saving. */
  read<T>(fn: (db: Readonly<Db>) => T): T;
  /** Run a change. It is saved only if `fn` returns without throwing. */
  write<T>(fn: (db: Db) => T): T;
  putFile(key: string, bytes: Uint8Array): void;
  getFile(key: string): Buffer | null;
  deleteFile(key: string): void;
}

/**
 * LOCAL MODE store: one JSON file plus an uploads folder.
 * Good for a single-machine pilot or demo. Not a production database.
 * All calls are synchronous, so one process cannot interleave two writes.
 */
export class FileDataStore implements DataStore {
  private dbFile: string;
  private uploadDir: string;

  constructor(dir: string) {
    this.dbFile = path.join(dir, "db.json");
    this.uploadDir = path.join(dir, "uploads");
    fs.mkdirSync(this.uploadDir, { recursive: true });
  }

  private load(): Db {
    if (!fs.existsSync(this.dbFile)) return emptyDb();
    return { ...emptyDb(), ...(JSON.parse(fs.readFileSync(this.dbFile, "utf8")) as Partial<Db>) };
  }

  read<T>(fn: (db: Readonly<Db>) => T): T {
    return fn(this.load());
  }

  write<T>(fn: (db: Db) => T): T {
    const db = this.load();
    const result = fn(db);
    const tmp = `${this.dbFile}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(db, null, 2));
    fs.renameSync(tmp, this.dbFile);
    return result;
  }

  private filePath(key: string): string {
    // Keys are generated by us (owner/uuid). Refuse anything that could leave the folder.
    if (!/^[0-9a-f-]{36}\/[0-9a-f-]{36}$/.test(key)) throw new Error("Bad storage key");
    return path.join(this.uploadDir, ...key.split("/"));
  }

  putFile(key: string, bytes: Uint8Array): void {
    const p = this.filePath(key);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, bytes);
  }

  getFile(key: string): Buffer | null {
    const p = this.filePath(key);
    return fs.existsSync(p) ? fs.readFileSync(p) : null;
  }

  deleteFile(key: string): void {
    fs.rmSync(this.filePath(key), { force: true });
  }
}

let shared: DataStore | undefined;

export function getStore(): DataStore {
  const g = globalThis as unknown as { __dynorexStore?: DataStore };
  if (!shared) {
    g.__dynorexStore ??= new FileDataStore(
      process.env.DYNOREX_DATA_DIR?.trim() || path.join(process.cwd(), ".data"),
    );
    shared = g.__dynorexStore;
  }
  return shared;
}
